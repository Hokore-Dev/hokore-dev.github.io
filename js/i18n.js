function currentLang() {
  return document.documentElement.dataset.lang || 'ko';
}

function t(key) {
  var dict = translations[currentLang()] || translations.ko;
  return dict[key] != null ? dict[key] : (translations.ko[key] || '');
}

function setLanguage(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dataset.lang = lang;

  var dict = translations[lang] || {};
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var value = dict[el.dataset.i18n];
    if (value != null) el.innerHTML = value;
  });

  document.querySelectorAll('.lang-switch button[data-lang]').forEach(function (btn) {
    var active = btn.dataset.lang === lang;
    btn.classList.toggle('is-active', active);
    btn.setAttribute('aria-pressed', String(active));
  });

  try { localStorage.setItem('lang', lang); } catch (e) { /* private mode */ }

  document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: lang } }));
}

function toggleLanguage() {
  setLanguage(currentLang() === 'ko' ? 'en' : 'ko');
}

(function () {
  var saved = 'ko';
  try { saved = localStorage.getItem('lang') || 'ko'; } catch (e) { /* private mode */ }
  setLanguage(saved);
})();
